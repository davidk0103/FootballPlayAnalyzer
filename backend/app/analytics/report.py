"""Deterministic scouting report: team vs league on offense and defense, plus findings.

No AI and no randomness: the same plays and parameters always produce the same report.
Findings are generated by fixed rules from ranks among the teams in the data, and only
when the sample is large enough; nothing is claimed to be statistically significant.
"""

from dataclasses import dataclass, field

import pandas as pd

from app.analytics.filters import FIELD_ZONE_RANGES, FieldZone
from app.analytics.frame import Side, flag
from app.analytics.metrics import (
    DEFAULT_THRESHOLDS,
    MetricValue,
    Thresholds,
    compute_team_metrics,
    efficiency_metrics,
    ratio,
    scrimmage_plays,
)
from app.analytics.tendencies import (
    TendencyCell,
    ThirdDownAnalysis,
    down_distance_grid,
    third_down_analysis,
)

# (metric, offense label, defense label)
REPORT_METRICS: tuple[tuple[str, str, str], ...] = (
    ("epa_per_play", "EPA/play", "EPA/play allowed"),
    ("success_rate", "Success rate", "Success rate allowed"),
    ("yards_per_play", "Yards/play", "Yards/play allowed"),
    ("third_down_conversion_rate", "3rd-down conversion", "3rd-down conversion allowed"),
    ("explosive_play_rate", "Explosive play rate", "Explosive play rate allowed"),
    ("turnovers_per_game", "Turnovers/game", "Takeaways/game"),
    ("pass_rate", "Pass rate", "Opponent pass rate"),
)
# For an offense, more is better except turnovers; pass rate is a style, not a grade.
LOWER_IS_BETTER_ON_OFFENSE = frozenset({"turnovers_per_game"})
UNGRADED = frozenset({"pass_rate"})
MIN_TEAMS_TO_RANK = 4
MIN_THIRD_DOWNS = 20
MAX_FINDINGS = 8
PASS_RATE_GAP = 0.05


@dataclass(frozen=True)
class ReportMetric:
    name: str
    label: str
    value: float | None
    numerator: float
    denominator: int
    league_value: float | None
    difference: float | None
    rank: int | None
    of: int | None
    better: str | None  # "higher" | "lower" | None (ungraded)


@dataclass(frozen=True)
class RedZone:
    plays: int
    epa_per_play: MetricValue
    success_rate: MetricValue
    touchdown_rate: MetricValue


@dataclass(frozen=True)
class SideReport:
    side: str
    plays: int
    games: int
    metrics: list[ReportMetric]
    third_down: ThirdDownAnalysis
    red_zone: RedZone
    league_red_zone: RedZone


@dataclass(frozen=True)
class Finding:
    side: str
    metric: str
    kind: str  # "strength" | "weakness" | "tendency"
    text: str


@dataclass
class ScoutingReport:
    offense: SideReport
    defense: SideReport
    tendencies: list[TendencyCell]
    findings: list[Finding]
    warnings: list[str] = field(default_factory=list)
    limitations: list[str] = field(default_factory=list)


@dataclass(frozen=True)
class Inputs:
    """Already filtered team_view frames (all play types) for one team and the league."""

    team: str
    offense: pd.DataFrame
    league_offense: pd.DataFrame
    defense: pd.DataFrame
    league_defense: pd.DataFrame


def _better(name: str, side: Side) -> str | None:
    if name in UNGRADED:
        return None
    higher = name not in LOWER_IS_BETTER_ON_OFFENSE
    if side == Side.DEFENSE:
        higher = not higher
    return "higher" if higher else "lower"


def _per_team(league: pd.DataFrame, thresholds: Thresholds) -> dict[str, dict[str, MetricValue]]:
    return {
        str(abbr): compute_team_metrics(plays, thresholds=thresholds).metrics
        for abbr, plays in league.groupby("team", observed=True)
    }


def _rank(values: dict[str, float], team: str, better: str) -> tuple[int | None, int | None]:
    if team not in values or len(values) < MIN_TEAMS_TO_RANK:
        return None, (len(values) or None)
    ordered = sorted(values.values(), reverse=better == "higher")
    return ordered.index(values[team]) + 1, len(values)


def red_zone(plays: pd.DataFrame) -> RedZone:
    """Scrimmage plays snapped inside the opponent's 20. TD rate is per play, not per trip
    (play-by-play data has no reliable drive boundaries for uploads)."""
    lo, hi = FIELD_ZONE_RANGES[FieldZone.RED_ZONE]
    zone = scrimmage_plays(plays)
    zone = zone[zone["yard_line_100"].between(lo, hi).fillna(False).astype(bool)]
    touchdowns = flag(zone["touchdown"]) & ~flag(zone["interception"]) & ~flag(zone["fumble_lost"])
    known_td = zone["touchdown"].notna()
    eff = efficiency_metrics(zone)
    return RedZone(
        plays=len(zone),
        epa_per_play=eff["epa_per_play"],
        success_rate=eff["success_rate"],
        touchdown_rate=ratio(float(touchdowns[known_td].sum()), int(known_td.sum())),
    )


def _side(
    team: str,
    side: Side,
    plays: pd.DataFrame,
    league: pd.DataFrame,
    thresholds: Thresholds,
) -> SideReport:
    mine = compute_team_metrics(plays, thresholds=thresholds)
    league_all = compute_team_metrics(league, thresholds=thresholds).metrics
    teams = _per_team(league, thresholds)
    turnovers = [m["turnovers_per_game"].value for m in teams.values()]
    known = [v for v in turnovers if v is not None]
    league_turnovers = round(sum(known) / len(known), 4) if known else None

    metrics = []
    for name, offense_label, defense_label in REPORT_METRICS:
        label = offense_label if side == Side.OFFENSE else defense_label
        value = mine.metrics[name]
        league_value = league_turnovers if name == "turnovers_per_game" else league_all[name].value
        better = _better(name, side)
        rank = of = None
        if better is not None:
            values = {t: v for t, m in teams.items() if (v := m[name].value) is not None}
            rank, of = _rank(values, team, better)
        metrics.append(
            ReportMetric(
                name=name,
                label=label,
                value=value.value,
                numerator=value.numerator,
                denominator=value.denominator,
                league_value=league_value,
                difference=(
                    round(value.value - league_value, 4)
                    if value.value is not None and league_value is not None
                    else None
                ),
                rank=rank,
                of=of,
                better=better,
            )
        )
    return SideReport(
        side=side.value,
        plays=mine.plays,
        games=mine.games,
        metrics=metrics,
        third_down=third_down_analysis(plays, league, team, side),
        red_zone=red_zone(plays),
        league_red_zone=red_zone(league),
    )


def _fmt(name: str, value: float) -> str:
    if name.endswith("_rate"):
        return f"{value * 100:.1f}%"
    if name == "epa_per_play":
        return f"{value:+.3f}"
    return f"{value:.2f}"


def _findings(report: SideReport, min_sample: int) -> list[tuple[float, int, Finding]]:
    side_label = report.side.capitalize()
    out: list[tuple[float, int, Finding]] = []
    if report.plays < min_sample:
        return out
    for order, m in enumerate(report.metrics):
        if m.value is None or m.league_value is None:
            continue
        if m.name == "third_down_conversion_rate" and m.denominator < MIN_THIRD_DOWNS:
            continue
        if m.name == "pass_rate":
            gap = m.value - m.league_value
            if abs(gap) >= PASS_RATE_GAP:
                more = "more" if gap > 0 else "less"
                text = (
                    f"{side_label} {'faces passes' if report.side == 'defense' else 'passes'} "
                    f"{more} often than the league average ({_fmt(m.name, m.value)} vs "
                    f"{_fmt(m.name, m.league_value)} of scrimmage plays, n={m.denominator})."
                )
                out.append((abs(gap), order, Finding(report.side, m.name, "tendency", text)))
            continue
        if m.rank is None or m.of is None:
            continue
        third = m.of / 3
        if m.rank <= third:
            kind = "strength"
        elif m.rank > m.of - third:
            kind = "weakness"
        else:
            continue
        text = (
            f"{side_label} {m.label}: {_fmt(m.name, m.value)} vs league "
            f"{_fmt(m.name, m.league_value)} (rank {m.rank} of {m.of}, n={m.denominator})."
        )
        extremity = abs(m.rank - (m.of + 1) / 2) / m.of
        out.append((extremity, order, Finding(report.side, m.name, kind, text)))
    return out


def build_report(
    inputs: Inputs,
    *,
    thresholds: Thresholds = DEFAULT_THRESHOLDS,
    min_sample: int = 30,
) -> ScoutingReport:
    offense = _side(inputs.team, Side.OFFENSE, inputs.offense, inputs.league_offense, thresholds)
    defense = _side(inputs.team, Side.DEFENSE, inputs.defense, inputs.league_defense, thresholds)
    ranked = _findings(offense, min_sample) + _findings(defense, min_sample)
    ranked.sort(key=lambda item: (-item[0], item[2].side, item[1]))
    findings = [f for _, _, f in ranked[:MAX_FINDINGS]]

    warnings: list[str] = []
    limitations = [
        "Comparisons describe this sample only; differences are not tested for "
        "statistical significance.",
        "League values are play-weighted averages over every team in the same data and "
        "filters; turnovers/game is the mean of per-team values.",
    ]
    for rep in (offense, defense):
        if rep.plays == 0:
            warnings.append(f"No {rep.side} plays match these filters")
        elif rep.plays < min_sample:
            warnings.append(
                f"Only {rep.plays} {rep.side} plays; findings need at least {min_sample}"
            )
    of = next((m.of for m in offense.metrics if m.of is not None), None)
    if of is not None and of < MIN_TEAMS_TO_RANK:
        limitations.append(
            f"Only {of} teams in the data; ranks and strength/weakness findings need at "
            f"least {MIN_TEAMS_TO_RANK}."
        )
    if offense.third_down.plays < MIN_THIRD_DOWNS:
        limitations.append(
            f"Third-down findings need at least {MIN_THIRD_DOWNS} third-down plays "
            f"(offense has {offense.third_down.plays})."
        )
    return ScoutingReport(
        offense=offense,
        defense=defense,
        tendencies=down_distance_grid(inputs.offense, inputs.league_offense),
        findings=findings,
        warnings=warnings,
        limitations=limitations,
    )
